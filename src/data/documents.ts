export const documentValidation = validateDocumentRegistry(
  documentDefinitions,
  documentClaims,
  primitives.research_sources.map((source) => source.id),
);

if (!documentValidation.valid) {
  const details = documentValidation.errors.map((issue) => `${issue.path}: ${issue.message}`).join("; ");
  throw new Error(`Invalid document registry: ${details}`);
}

export const claimsByDocument = documentClaims.reduce<Record<DocumentId, Claim[]>>((result, claim) => {
  result[claim.documentId] ??= [];
  result[claim.documentId].push(claim);
  return result;
}, {} as Record<DocumentId, Claim[]>);
